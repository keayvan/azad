const dict: Record<Lang, Record<string, string>> = { en, fa };

export function useT() {
  const { lang } = useStore();
  const t = (key: string, vars?: Record<string, string | number>): string => {
    let s = dict[lang][key] ?? dict.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
  const locale = lang === 'fa' ? 'fa-IR' : 'en-GB';
  const num = (n: number, digits = 0) => new Intl.NumberFormat(locale, { maximumFractionDigits: digits }).format(n);
  const date = (ms: number) => new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short' }).format(ms);
  return { t, lang, num, date };
}
